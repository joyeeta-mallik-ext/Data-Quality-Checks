# =========================================================

def main(input_file: str, run_id: Optional[str] = None) -> str:
    """
    Definition:
        Main execution function. Loads the exact input CSV path supplied by the
        orchestrator, runs LLM rule generation/execution, and saves Excel output.

    Input:
        input_file: CSV path produced by Predifined_Rule_Checks.py.
        run_id: Optional common run id supplied by orchestrator.

    Output:
        Generated AI Excel file path.
    """
    ensure_output_folders()

    if run_id is None:
        run_id = datetime.now().strftime("%Y%m%d_%H%M%S")

    all_results: List[Dict[str, Any]] = []

    print("\nSQL Generation Started\n")

    input_df = load_input_dataset(input_file)
    input_df = normalize_dataframe_columns(input_df)

    if "ENTITY" not in input_df.columns:
        input_df["ENTITY"] = ""

    if "SQL_QUERIES" not in input_df.columns:
        input_df["SQL_QUERIES"] = ""

    if "TASK" not in input_df.columns:
        input_df["TASK"] = ""

    processing_df = (
        input_df[["TABLE", "ENTITY", "COLUMN"]]
        .dropna(subset=["TABLE", "COLUMN"])
        .drop_duplicates()
        .reset_index(drop=True)
    )

    with ThreadPoolExecutor(max_workers=1) as executor:
        future_to_task: Dict[Any, Tuple[str, str]] = {}

        for _, row in processing_df.iterrows():
            table_name = str(row["TABLE"]).strip()
            entity_value = str(row["ENTITY"]).strip()
            column_name = str(row["COLUMN"]).strip()

            existing_tasks, existing_sqls = get_existing_values_for_column(
                input_df=input_df,
                table_name=table_name,
                column_name=column_name,
            )

            first_existing_sql = existing_sqls[0] if existing_sqls else ""
            try:
                if table_name.upper() == "MDM_HCO_ADDR_DATA_FULL" and column_name.upper() == "STATE":
                    full_table_name = (
                        f"{SNOWFLAKE_CREDS['database']}."
                        f"{SNOWFLAKE_CREDS['schema']}."
                        f"{table_name}"
                    )
                else:
                    full_table_name = extract_full_table_name_from_sql(
                        sql_text=first_existing_sql,
                        fallback_table=table_name,
                    )
            except Exception:
                full_table_name = extract_full_table_name_from_sql(
                    sql_text=first_existing_sql,
                    fallback_table=table_name,
                )

            future = executor.submit(
                run_pipeline,
                table_name,
                column_name,
                entity_value,
                full_table_name,
                existing_tasks,
                existing_sqls,
            )

            future_to_task[future] = (table_name, column_name)

        for future in as_completed(future_to_task):
            table_name, column_name = future_to_task[future]

            try:
                result_rows = future.result()
                all_results.extend(result_rows)

                print(f"Completed: {table_name}.{column_name}")

            except Exception as exc:
                print(f"Error in {table_name}.{column_name}: {exc}")

    output_file = save_results(all_results, run_id=run_id)
    print("\nLLM rule generation DONE")
    return output_file


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Run LLM rule checks using predefined-rule CSV input.")
    parser.add_argument("--input-file", required=True, help="CSV file generated by Predifined_Rule_Checks.py")
    parser.add_argument("--run-id", required=False, default=None, help="Optional common run id")
    args = parser.parse_args()

    main(input_file=args.input_file, run_id=args.run_id)
