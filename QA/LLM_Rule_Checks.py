def save_results(results: List[Dict[str, Any]], run_id: Optional[str] = None) -> str:
    """
    Definition:
        Saves final DQ SQL and impact results to timestamped Excel file.

    Input:
        results: List of result dictionaries from run_pipeline().
        run_id: Optional common run id supplied by orchestrator.

    Output:
        File path of the generated Excel output.
    """
    ensure_output_folders()

    if run_id is None:
        run_id = datetime.now().strftime("%Y%m%d_%H%M%S")

    df = pd.DataFrame(results)
    file_name = os.path.join(AI_OUTPUT_DIR, f"dqc_sql_only_{run_id}.xlsx")
    df.to_excel(file_name, index=False)
    keep_latest_files(AI_OUTPUT_DIR, keep_count=2)
    print(f"\nSQLs saved to file: {file_name}")
    return file_name


def get_existing_values_for_column(
    input_df: pd.DataFrame,
    table_name: str,
    column_name: str,
) -> Tuple[List[str], List[str]]:
    """
    Definition:
        Gets existing TASK and SQL_QUERIES values for the same TABLE + COLUMN.

    Input:
        input_df: Normalized input DataFrame.
        table_name: Table name being processed.
        column_name: Column name being processed.

    Output:
        Tuple containing existing_tasks list and existing_sqls list.
    """
    same_col_df = input_df[
        (input_df["TABLE"].astype(str).str.strip().str.upper() == table_name.upper())
        & (input_df["COLUMN"].astype(str).str.strip().str.upper() == column_name.upper())
    ]

    existing_tasks = (
        same_col_df["TASK"]
        .dropna()
        .astype(str)
        .str.strip()
        .replace("", pd.NA)
        .dropna()
        .unique()
        .tolist()
    )

    existing_sqls = (
        same_col_df["SQL_QUERIES"]
        .dropna()
        .astype(str)
        .str.strip()
        .replace("", pd.NA)
        .dropna()
        .unique()
        .tolist()
    )

    return existing_tasks, existing_sqls


