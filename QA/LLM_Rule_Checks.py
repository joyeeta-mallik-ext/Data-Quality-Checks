def clean_sql(sql: Optional[str]) -> str:
    """
    Definition:
        Cleans SQL text returned by the LLM or read from input files.

    Input:
        sql: SQL string or None.

    Output:
        Clean SQL string.
    """
    if not sql:
        return ""

    sql = str(sql).strip()

    if sql.startswith("```"):
        sql = sql.replace("```sql", "").replace("```", "")

    return sql.strip()


def normalize_sample_value(value: Any) -> str:
    """
    Definition:
        Converts Snowflake sample values into consistent tokens.

    Input:
        value: Any value fetched from Snowflake for a sample column.

    Output:
        String representation of the value.
    """
    if value is None:
        return "NULL"

    value_as_string = str(value)

    if value_as_string == "":
        return "BLANK"

    if value_as_string.strip() == "":
        return "WHITESPACE_ONLY"

    return value_as_string.strip()


def normalize_dataframe_columns(df: pd.DataFrame) -> pd.DataFrame:
    """
    Definition:
        Standardizes DataFrame column names to uppercase strings with trimmed whitespace.

    Input:
        df: Pandas DataFrame.

    Output:
        New DataFrame copy with normalized column names.
    """
    normalized_df = df.copy()
    normalized_df.columns = [str(col).upper().strip() for col in normalized_df.columns]
    return normalized_df


def safe_string_series(series: pd.Series) -> pd.Series:
    """
    Definition:
        Converts a pandas Series into clean strings and removes empty strings.

    Input:
        series: Pandas Series.

    Output:
        Cleaned pandas Series.
    """
    return series.dropna().astype(str).str.strip().replace("", pd.NA).dropna()


