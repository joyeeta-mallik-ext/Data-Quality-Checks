def derive_entity_and_category(entity_name: str) -> Tuple[str, str]:
    """
    Definition:
        Derives entity type and category from an entity name pattern.

    Input:
        entity_name: Entity name string.

    Output:
        Tuple containing entity_type and category.
    """
    entity_type = "UNKNOWN"
    category = "UNKNOWN"

    entity_name = str(entity_name).upper().strip()

    if entity_name.startswith("HCP_"):
        entity_type = "HCP"
    elif entity_name.startswith("HCO_"):
        entity_type = "HCO"

    if entity_name.endswith("_PROFILE"):
        category = "PROFILE"
    elif entity_name.endswith("_ADDRESS"):
        category = "ADDRESS"
    elif entity_name.endswith("_LICENSE"):
        category = "LICENSE"

    return entity_type, category


def derive_entity_and_category_from_df(table: str, entity_value: Optional[str] = None) -> Tuple[str, str]:
    """
    Definition:
        Derives business entity display name and category from table name.

    Input:
        table: Source table name.
        entity_value: Optional entity value from input file.

    Output:
        Tuple containing entity display name and category.
    """
    table_upper = str(table).upper().strip()
    return TABLE_ENTITY_MAP.get(table_upper, ("UNKNOWN", "UNKNOWN"))


def get_unique_failed_count(df: pd.DataFrame) -> int:
    """
    Definition:
        Calculates IMPACTED_UNIQUE_SOURCE_ID_COUNT using unique SOURCE_ID values.

    Input:
        df: DataFrame returned by the failed/problematic-record SQL query.

    Output:
        Integer count of unique non-null, non-blank SOURCE_ID values.
    """
    if df is None or df.empty:
        return 0

    temp_df = normalize_dataframe_columns(df)

    if "SOURCE_ID" not in temp_df.columns:
        return 0

    return safe_string_series(temp_df["SOURCE_ID"]).nunique()


def build_source_cd_summary(df: pd.DataFrame, total_impacted_count: Optional[int] = None) -> str:
    """
    Definition:
        Builds SOURCE_CD_SUMMARY using unique SOURCE_ID impact per SOURCE_CD.

    Input:
        df: DataFrame returned by the executed SQL query.
        total_impacted_count: Optional total unique failed SOURCE_ID count.

    Output:
        Formatted source breakdown string.
    """
    if df is None or df.empty:
        return ""

    temp_df = normalize_dataframe_columns(df)

    required_columns = {"SOURCE_CD", "SOURCE_ID"}
    if not required_columns.issubset(set(temp_df.columns)):
        return ""

    temp_df = temp_df.copy()
    temp_df["SOURCE_CD"] = temp_df["SOURCE_CD"].astype(str).str.strip().replace("", pd.NA)
    temp_df["SOURCE_ID"] = temp_df["SOURCE_ID"].astype(str).str.strip().replace("", pd.NA)
    temp_df = temp_df.dropna(subset=["SOURCE_CD", "SOURCE_ID"])

    if temp_df.empty:
        return ""

    if total_impacted_count is None:
        total_impacted_count = get_unique_failed_count(temp_df)

    if total_impacted_count == 0:
        return ""

    summary_df = (
        temp_df.groupby("SOURCE_CD", dropna=True)["SOURCE_ID"]
        .nunique()
        .reset_index(name="IMPACTED_UNIQUE_SOURCE_ID_COUNT")
        .sort_values(by="IMPACTED_UNIQUE_SOURCE_ID_COUNT", ascending=False)
    )

    output_parts = []

    for _, row in summary_df.iterrows():
        source_cd = str(row["SOURCE_CD"])
        impacted_count = int(row["IMPACTED_UNIQUE_SOURCE_ID_COUNT"])
        impacted_pct = (impacted_count / total_impacted_count) * 100
        output_parts.append(f"{source_cd}({impacted_count},{impacted_pct:.2f}%)")

    return "; ".join(output_parts)


