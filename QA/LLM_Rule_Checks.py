def call_llm(messages: List[Dict[str, str]]) -> str:
    """
    Definition:
        Calls the internal LLM endpoint with retry and exponential backoff.

    Input:
        messages: List of role/content dictionaries for chat completion.

    Output:
        LLM response content as string.
    """
    headers = {
        "Authorization": f"Bearer {API_KEY}",
        "Content-Type": "application/json",
    }

    payload = {
        "model": LLM_MODEL,
        "messages": messages,
        "temperature": 0,
    }

    delay_seconds = 2

    for attempt in range(LLM_MAX_RETRIES):
        try:
            response = requests.post(
                LLM_URL,
                headers=headers,
                json=payload,
                proxies=PROXIES,
                verify=False,
                timeout=LLM_TIMEOUT_SECONDS,
            )
            response.raise_for_status()
            return response.json()["choices"][0]["message"]["content"]

        except Exception as exc:
            print(f"LLM attempt {attempt + 1} failed: {exc}")
            time.sleep(delay_seconds)
            delay_seconds *= 2

    raise Exception("LLM failed after retries")


def generate_analysis_sql(
    full_table_name: str,
    column: str,
    sample_data: List[str],
    existing_tasks: Optional[List[str]] = None,
    existing_sqls: Optional[List[str]] = None,
) -> List[Dict[str, Any]]:
    """
    Definition:
        Generates additional Snowflake data quality SQL checks for a given column.

    Input:
        full_table_name: Fully qualified Snowflake table name.
        column: Column being analyzed.
        sample_data: Observed sample values from the column.
        existing_tasks: Existing task names for the same table/column.
        existing_sqls: Existing SQL queries for the same table/column.

    Output:
        List of dictionaries returned by the LLM.
    """
    existing_tasks = existing_tasks or []
    existing_sqls = existing_sqls or []

    if not sample_data:
        return [
            {
                "name": "NO_VALUE_AVAILABLE",
                "sql": "",
                "rule_description": "No value available for analysis",
                "failed_count_sql": "",
                "Insight": "No value available for analysis",
            }
        ]

    print(f"Generating additional SQLs for {column} using AI")
    print("@@@@@@@@@@TEST 4")
    prompt = f"""Generate additional Snowflake Data Quality SQL queries for column {column} in table {full_table_name}.
    Observed Sample Values:
    {sample_data[:30]}
    

Interpretation:
- NULL = actual NULL values
- BLANK = empty string ('')
- WHITESPACE_ONLY = values containing only spaces

Existing Coverage:
TASKS: {existing_tasks}
SQL_QUERIES: {existing_sqls}

Do not duplicate, recreate, or generate rules that are identical, equivalent, or already covered by existing TASKS or SQL_QUERIES. Use them to identify gaps and generate only new meaningful checks for this column.

Objective:
Identify realistic data quality anomalies only from observed data patterns. Treat NULL, BLANK, and WHITESPACE_ONLY as valid observed patterns when present. Avoid generic, theoretical, or unsupported validations.

SQL Requirements:
- Maximum 5 queries
- Each query must represent a unique DQ issue
- Simple, readable Snowflake SQL
- No SELECT *
- Avoid heavy joins
- Return only failed/problematic records
- Use exact table name: {full_table_name}
- Include SOURCE_ID when available for unique impact counting
- Include SOURCE_CD when available for traceability

Business Rules:
- Do not create case-sensitivity checks (uppercase/lowercase)
- Do not create singular/plural variation checks
- Do not enforce address length restrictions
- For Source_ID analysis, flag only records whose pattern deviates from other records within the same SOURCE_CD; differences across SOURCE_CD values are expected
- Do not generate Source_ID, Source_CD, Primary Key, ADDRESS_ID, LICENSE_ID, or PRMRY_KEY as standalone analysis columns
- Special characters in Specialty Code (/, -, ,) are valid
- Verify IDENTIFIER_VALUE and IDENTIFIER_TYPE consistency
- Verify STATE + ZIP + CITY combinations and immediately flag mismatches
- Flag ORGNAME values appearing in HCP datasets
- Skip XPNT_PRSC_ID as IDENTIFIER_TYPE in LICENSE tables

Strict Filters:
- Generate rules only when failures are likely to exist
- Do not assume unseen patterns
- Do not generate null checks already covered by existing TASKS/SQL_QUERIES
- Do not generate format validations already covered by existing TASKS/SQL_QUERIES

Rule Generation Process:
1. Identify a visible inconsistency, anomaly, mismatch, missing relationship, invalid combination, or pattern deviation.
2. Generate SQL targeting only failed records.

Fallback:
If no additional meaningful checks exist, return [].

Return ONLY valid JSON:

[
  {{
    "name": "<short business-friendly and user friendly issue description>",
    "sql": "<snowflake sql>",
    "rule_description": "<business-friendly DQ rule>",
    "Insight": "<reason for rule generation and expected impact with detailed explanation>"
  }}
]
"""
    print("@@@@@@@@@@TEST 3")
    messages = [
        {"role": "system", "content": "Return ONLY valid JSON. Do not include markdown."},
        {"role": "user", "content": prompt},
    ]

    try:
        print("@@@@@@@@@@TEST 1")
        response = clean_sql(call_llm(messages))
        parsed_response = json.loads(response)
        print("@@@@@@@@@@TEST 2")
        return parsed_response if isinstance(parsed_response, list) else []


    except Exception as exc:
        print(f"LLM parse error for {column}: {exc}")
        return []


def fix_sql_with_llm(original_sql: str, error_message: str) -> str:
    """
    Definition:
        Uses the LLM to fix Snowflake SQL errors while preserving business logic.

    Input:
        original_sql: SQL that failed during execution.
        error_message: Snowflake error message returned for the failed SQL.

    Output:
        Corrected SQL string returned by the LLM.
    """
    prompt = f"""
The following Snowflake SQL has an error.

SQL:
{original_sql}

ERROR:
{error_message}

Fix the SQL so that it runs correctly in Snowflake.

Rules:
- Preserve intent of original SQL
- Fix syntax, regex, column names
- Do NOT invent new tables

Return ONLY corrected SQL.
"""

    messages = [
        {"role": "system", "content": "You fix SQL errors."},
        {"role": "user", "content": prompt},
    ]

    return clean_sql(call_llm(messages))


