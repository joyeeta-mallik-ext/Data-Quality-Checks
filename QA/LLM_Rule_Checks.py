def load_input_dataset(input_file: str) -> pd.DataFrame:
    """
    Definition:
        Reads the exact predefined-rule CSV file passed by run_full_pipeline.py.
        This avoids fragile glob/latest-file selection.

    Input:
        input_file: CSV file path produced by Predifined_Rule_Checks.py.

    Output:
        Pandas DataFrame containing the input rules/context.

    Raises:
        FileNotFoundError if input_file is not available.
        ValueError if required columns are missing.
    """
    if not input_file:
        raise ValueError("input_file is required for LLM_Rule_Checks.py")

    if not os.path.exists(input_file):
        raise FileNotFoundError(f"Input CSV file not found: {input_file}")

    print(f"Using input file: {input_file}")

    df = pd.read_csv(input_file)
    df.columns = [str(col).strip().upper() for col in df.columns]

    if "SQL_QUERIES" not in df.columns and "SQL_QUERY" in df.columns:
        df["SQL_QUERIES"] = df["SQL_QUERY"]

    required_cols = ["TABLE", "COLUMN", "TASK"]
    missing_cols = [col for col in required_cols if col not in df.columns]

    if "SQL_QUERY" not in df.columns and "SQL_QUERIES" not in df.columns:
        missing_cols.append("SQL_QUERY or SQL_QUERIES")

    if missing_cols:
        raise ValueError(f"Missing required columns in input CSV file: {missing_cols}")

    return df


def extract_full_table_name_from_sql(sql_text: Any, fallback_table: str) -> str:
    """
    Definition:
        Extracts the table name used in existing SQL or falls back to env database/schema/table.

    Input:
        sql_text: Existing SQL text from the input file.
        fallback_table: Table name from the TABLE column.

    Output:
        Fully qualified table name.
    """
    default_full_table = f"{SNOWFLAKE_CREDS['database']}.{SNOWFLAKE_CREDS['schema']}.{fallback_table}"

    if pd.isna(sql_text) or not str(sql_text).strip():
        return default_full_table

    sql_text = str(sql_text)
    pattern = r"\b(?:FROM|JOIN)\s+([A-Za-z0-9_.$\"]+(?:\.[A-Za-z0-9_.$\"]+){0,2})"
    match = re.search(pattern, sql_text, flags=re.IGNORECASE)

    if not match:
        return default_full_table

    table_ref = match.group(1).replace('"', "").strip()

    if table_ref.count(".") == 2:
        return table_ref

    if table_ref.count(".") == 1:
        return f"{SNOWFLAKE_CREDS['database']}.{table_ref}"

    return f"{SNOWFLAKE_CREDS['database']}.{SNOWFLAKE_CREDS['schema']}.{table_ref}"


def get_table_parts(full_table_name: str) -> Tuple[str, str, str]:
    """
    Definition:
        Splits a full table reference into database, schema, and table parts.

    Input:
        full_table_name: Table reference.

    Output:
        Tuple containing database name, schema name, and table name.
    """
    parts = full_table_name.replace('"', "").split(".")

    if len(parts) == 3:
        return parts[0], parts[1], parts[2]

    if len(parts) == 2:
        return SNOWFLAKE_CREDS["database"], parts[0], parts[1]

    return SNOWFLAKE_CREDS["database"], SNOWFLAKE_CREDS["schema"], parts[0]


