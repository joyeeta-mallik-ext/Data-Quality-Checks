def run_pipeline(
    table: str,
    column: str,
    entity_value: str,
    full_table_name: str,
    existing_tasks: List[str],
    existing_sqls: List[str],
) -> List[Dict[str, Any]]:
    """
    Definition:
        Runs complete DQ rule generation and execution for one TABLE + COLUMN.

    Input:
        table: Source table name from input CSV.
        column: Column being analyzed.
        entity_value: Entity value from input CSV.
        full_table_name: Fully qualified Snowflake table name.
        existing_tasks: Existing tasks for this table/column.
        existing_sqls: Existing SQL strings for this table/column.

    Output:
        List of dictionaries. Each dictionary is one final output row.
    """
    print(f"\nProcessing: {full_table_name}.{column}")

    entity_name, _ = derive_entity_and_category_from_df(table, entity_value)
    conn = get_connection(os.getenv("private_key_text"), os.getenv("passphrase"), os.getenv("SNOW_ACCOUNT"), os.getenv("SNOW_USER"),
                          os.getenv("SNOW_DB"), os.getenv("SNOW_WH"), os.getenv("SNOW_SCHEMA"),os.getenv("SNOW_ROLE"), key='cursor')

    def run_query(query: str) -> Tuple[pd.DataFrame, Optional[str]]:
        cur = conn.cursor()
        try:
            cur.execute(query)
            query_df = cur.fetch_pandas_all()
            return query_df, None
        except Exception as exc:
            return pd.DataFrame(), str(exc)
        finally:
            cur.close()

    def get_total_table_row_count() -> int:
        count_sql = f"SELECT COUNT(*) AS TOTAL_ROWS FROM {full_table_name}"
        df_count, error = run_query(count_sql)

        if error or df_count.empty:
            return 0

        try:
            return int(df_count.iloc[0, 0])
        except Exception:
            return 0

    def column_exists(column_name: str) -> bool:
        db_name, schema_name, table_name = get_table_parts(full_table_name)

        check_query = f"""
        SELECT COUNT(*)
        FROM {db_name}.INFORMATION_SCHEMA.COLUMNS
        WHERE TABLE_SCHEMA = '{schema_name.upper()}'
          AND TABLE_NAME = '{table_name.upper()}'
          AND COLUMN_NAME = '{column_name.upper()}'
        """

        df_check, error = run_query(check_query)

        if error or df_check.empty:
            return False

        return int(df_check.iloc[0, 0]) > 0

    def get_sample_data(sample_column: str) -> List[str]:
        cur = conn.cursor()

        try:
            has_source_cd = column_exists("SOURCE_CD")

            if has_source_cd:
                sample_query = f"""
                (
                    SELECT {sample_column}, SOURCE_CD
                    FROM {full_table_name}
                    WHERE {sample_column} IS NULL
                    LIMIT 10
                )
                UNION ALL
                (
                    SELECT {sample_column}, SOURCE_CD
                    FROM {full_table_name}
                    WHERE {sample_column} IS NOT NULL
                    QUALIFY ROW_NUMBER() OVER
                    (
                        PARTITION BY SOURCE_CD
                        ORDER BY RANDOM()
                    ) <= 5
                )
                """
            else:
                sample_query = f"""
                (
                    SELECT {sample_column}
                    FROM {full_table_name}
                    WHERE {sample_column} IS NULL
                    LIMIT 10
                )
                UNION ALL
                (
                    SELECT DISTINCT {sample_column}
                    FROM {full_table_name}
                    WHERE {sample_column} IS NOT NULL
                    LIMIT 40
                )
                """

            cur.execute(sample_query)
            rows = cur.fetchall()
            return [normalize_sample_value(row[0]) for row in rows if row]

        except Exception as exc:
            print(f"Sampling failed for {full_table_name}.{sample_column}: {exc}")
            return []

        finally:
            cur.close()

    try:
        total_table_rows = get_total_table_row_count()
        sample_data = get_sample_data(column)

        if not sample_data:
            return [
                {
                    "TABLE": table,
                    "COLUMN": column,
                    "ENTITY": entity_name,
                    "SOURCE_CD_SUMMARY": "",
                    "TASK": "NO_VALUE_AVAILABLE",
                    "SQL_QUERY": "",
                    "IMPACTED_UNIQUE_SOURCE_ID_COUNT": 0,
                    "TOTAL_TABLE_ROWS": total_table_rows,
                    "SAMPLE_RESULT": "",
                    "INSIGHT": "No value available for analysis",
                    "STATUS": "SKIPPED",
                }
            ]

        sql_list = generate_analysis_sql(
            full_table_name=full_table_name,
            column=column,
            sample_data=sample_data,
            existing_tasks=existing_tasks,
            existing_sqls=existing_sqls,
        )

        results: List[Dict[str, Any]] = []

        for item in sql_list:
            if not isinstance(item, dict):
                continue

            task = item.get("name", "UNKNOWN")
            sql = clean_sql(item.get("sql", ""))

            if not sql:
                continue

            if task == "NO_VALUE_AVAILABLE":
                results.append(
                    {
                        "TABLE": table,
                        "COLUMN": column,
                        "ENTITY": entity_name,
                        "SOURCE_CD_SUMMARY": "",
                        "TASK": "NO_VALUE_AVAILABLE",
                        "SQL_QUERY": "",
                        "IMPACTED_UNIQUE_SOURCE_ID_COUNT": 0,
                        "TOTAL_TABLE_ROWS": total_table_rows,
                        "SAMPLE_RESULT": "",
                        "INSIGHT": "No value available for analysis",
                        "STATUS": "SKIPPED",
                    }
                )
                continue

            df, error = run_query(sql)

            if error:
                print("Attempting SQL auto-fix")
                try:
                    fixed_sql = fix_sql_with_llm(sql, error)
                    fixed_df, fixed_error = run_query(fixed_sql)

                    if not fixed_error:
                        sql = fixed_sql
                        df = fixed_df
                        error = None
                    else:
                        error = fixed_error

                except Exception as exc:
                    print(f"Auto-fix failed: {exc}")

            failed_count = get_unique_failed_count(df)

            if failed_count == 0:
                continue

            source_cd_summary = build_source_cd_summary(df=df, total_impacted_count=failed_count)
            sample = df.head(3).to_dict(orient="records") if df is not None and not df.empty else []

            insight = f"Rule: {item.get('rule_description')}. "
            insight += f"Unique failed records = {failed_count}. "
            insight += f"Total rows in table = {total_table_rows}. "

            results.append(
                {
                    "TABLE": table,
                    "COLUMN": column,
                    "ENTITY": entity_name,
                    "SOURCE_CD_SUMMARY": source_cd_summary,
                    "TASK": task,
                    "SQL_QUERY": sql,
                    "IMPACTED_UNIQUE_SOURCE_ID_COUNT": failed_count,
                    "TOTAL_TABLE_ROWS": total_table_rows,
                    "SAMPLE_RESULT": str(sample),
                    "INSIGHT": insight,
                    "STATUS": "SUCCESS" if not error else "FAILED",
                }
            )

        return results

    finally:
        conn.close()


